def _normalize_unicode_for_export(text: str) -> str:
    """
    Replace Unicode replacement characters and common encoding artifacts with
    appropriate ASCII/Unicode equivalents to prevent black squares in exports.
    """
    if not text:
        return text

    replacements = {
        "\ufffd": "",
        "\u25a0": "",
        "\u25aa": "",
        "\u2022": "*",
        "\u2013": "-",
        "\u2014": "--",
        "\u2018": "'",
        "\u2019": "'",
        "\u201c": '"',
        "\u201d": '"',
        "\u2026": "...",
        "\u00a0": " ",
        "\ufb00": "ff",
        "\ufb01": "fi",
        "\ufb02": "fl",
        "\ufb03": "ffi",
        "\ufb04": "ffl",
    }

    for old, new in replacements.items():
        text = text.replace(old, new)

    return text


def normalize_export_font_family(value: object | None) -> str:
    normalized = str(value or "").strip().lower()
    return normalized if normalized in EXPORT_FONT_FAMILIES else DEFAULT_EXPORT_FONT_FAMILY


def export_font_label(font_family: object | None) -> str:
    return EXPORT_FONT_FAMILIES[normalize_export_font_family(font_family)]["label"]


def export_font_notice(font_family: object | None = None) -> str:
    normalized = normalize_export_font_family(font_family)
    font = EXPORT_FONT_FAMILIES[normalized]
    return "\n".join(
        [
            "LoreVia Font Notice",
            "",
            f"Selected export font: {font['label']}",
            "",
            font["notice"],
            (
                "PDF exports use built-in PDF font mappings unless an open font file is explicitly bundled. "
                "DOCX and EPUB exports declare the selected font family and allow the reader's device or app "
                "to choose an installed matching font or fallback."
            ),
            (
                "EB Garamond notice: Copyright 2017 The EB Garamond Project Authors "
                "(https://github.com/octaviopardo/EBGaramond12). Licensed under the SIL Open Font License, "
                "Version 1.1: https://openfontlicense.org."
            ),
        ]
    )


def _export_font_docx_name(font_family: object | None, default: str = "Times New Roman") -> str:
    normalized = normalize_export_font_family(font_family)
    if normalized == DEFAULT_EXPORT_FONT_FAMILY:
        return default
    return EXPORT_FONT_FAMILIES[normalized]["docx_font"]


def _export_font_epub_stack(font_family: object | None) -> str:
    return EXPORT_FONT_FAMILIES[normalize_export_font_family(font_family)]["epub_stack"]


def _export_font_pdf_names(font_family: object | None) -> tuple[str, str]:
    font = EXPORT_FONT_FAMILIES[normalize_export_font_family(font_family)]
    return font["pdf_regular"], font["pdf_bold"]


def _clean_line(value: object | None) -> str:
    return " ".join(str(value or "").split()).strip()


def _safe_name(value: object | None) -> str:
    cleaned = _clean_line(value)
    return (
        "".join(ch for ch in cleaned if ch.isalnum() or ch in {" ", "-", "_", "(", ")"})
        .strip()
        .replace(" ", "-")
    )


def export_filename_base(value: object | None, fallback: str = "lorevia") -> str:
    return _safe_name(value) or _safe_name(fallback) or "lorevia"


def append_export_attribution(text: str) -> str:
    stripped = text.rstrip()
    if not stripped:
        return EXPORT_ATTRIBUTION
    if stripped.endswith(EXPORT_ATTRIBUTION):
        return stripped
    return f"{stripped}\n\n{EXPORT_ATTRIBUTION}"


def _set_docx_core_properties(
    doc: Any, *, title: str, author: str = "LoreVia", subject: str | None = None
) -> None:
    core = doc.core_properties
    core.title = _clean_line(title) or "LoreVia Export"
    core.author = _clean_line(author) or "LoreVia"
    if subject is not None:
        core.subject = _clean_line(subject)
    core.comments = EXPORT_ATTRIBUTION


def _apply_pdf_metadata(
    canvas: Any, *, title: str, author: str = "LoreVia", subject: str | None = None
) -> None:
    safe_title = _clean_line(title) or "LoreVia Export"
    safe_author = _clean_line(author) or "LoreVia"
    safe_subject = _clean_line(subject)
    if hasattr(canvas, "setTitle"):
        canvas.setTitle(safe_title)
    if hasattr(canvas, "setAuthor"):
        canvas.setAuthor(safe_author)
    if safe_subject and hasattr(canvas, "setSubject"):
        canvas.setSubject(safe_subject)
    if hasattr(canvas, "setCreator"):
        canvas.setCreator("LoreVia")
