def _clean_line(value: object | None) -> str:
    return " ".join(str(value or "").split()).strip()


def _safe_name(value: object | None) -> str:
    cleaned = _clean_line(value)
    return "".join(ch for ch in cleaned if ch.isalnum() or ch in {" ", "-", "_", "(", ")"}).strip().replace(" ", "-")


def export_filename_base(value: object | None, fallback: str = "lorevia") -> str:
    return _safe_name(value) or _safe_name(fallback) or "lorevia"


def _set_docx_core_properties(doc: Any, *, title: str, author: str = "LoreVia", subject: str | None = None) -> None:
    core = doc.core_properties
    core.title = _clean_line(title) or "LoreVia Export"
    core.author = _clean_line(author) or "LoreVia"
    if subject is not None:
        core.subject = _clean_line(subject)
    core.comments = EXPORT_ATTRIBUTION


def _apply_pdf_metadata(canvas: Any, *, title: str, author: str = "LoreVia", subject: str | None = None) -> None:
    safe_title = _clean_line(title) or "LoreVia Export"
    safe_author = _clean_line(author) or "LoreVia"
    safe_subject = _clean_line(subject)
    if hasattr(canvas, "setTitle"):
        canvas.setTitle(safe_title)
    if hasattr(canvas, "setAuthor"):
        canvas.setAuthor(safe_author)
    if safe_subject and hasattr(canvas, "setSubject"):
        canvas.setSubject(safe_subject)
    if hasattr(canvas, "setCreator"):
        canvas.setCreator("LoreVia")


def _vault_note_title(value: object | None) -> str:
    cleaned = _clean_line(value)
    return cleaned or "Untitled"


def _vault_safe_name(value: object | None) -> str:
    cleaned = _vault_note_title(value)
    safe = "".join(ch for ch in cleaned if ch.isalnum() or ch in {" ", "-", "_", "(", ")"}).strip()
    return safe or "Untitled"


def _vault_link(title: str) -> str:
    return f"[[{title}]]"


def _normalize_lookup(value: object) -> str:
    return re.sub(r"\s+", " ", str(value)).strip().lower()


def _to_int(value: object | None, default: int = 0) -> int:
    try:
        if value is None:
            return default
        if isinstance(value, int):
            return value
        if isinstance(value, float):
            return int(value)
        if isinstance(value, str):
            return int(value)
        return default
    except (TypeError, ValueError):
        return default


def _build_link_targets(characters: list[Character]) -> dict[str, str]:
    targets: dict[str, str] = {}
    for char in characters:
        if not char.name:
            continue
        title = _vault_note_title(char.name)
        targets.setdefault(_normalize_lookup(char.name), title)
        for alias in char.aliases or []:
            alias_key = _normalize_lookup(alias)
            if alias_key:
                targets.setdefault(alias_key, title)
    return targets


def _character_reference_keys(char: Character) -> set[str]:
    keys = {_normalize_lookup(char.name), str(char.id).strip().lower()}
    keys.update(_normalize_lookup(alias) for alias in (char.aliases or []) if _clean_line(alias))
    return {key for key in keys if key}


def _find_character_reference(
    value: object,
    characters: list[Character],
    *,
    keys_by_character: dict[str, set[str]] | None = None,
) -> Character | None:
    normalized = _normalize_lookup(value)
    if not normalized:
        return None
    for char in characters:
        keys = keys_by_character.get(str(char.id), set()) if keys_by_character else _character_reference_keys(char)
        if normalized in keys:
            return char
    return None


def _character_names_from_values(
    values: Iterable[object] | None,
    characters: list[Character],
    *,
    keys_by_character: dict[str, set[str]] | None = None,
) -> list[str]:
    names: list[str] = []
    seen: set[str] = set()
    for value in values or []:
        match = _find_character_reference(value, characters, keys_by_character=keys_by_character)
        if match is not None and match.name and match.name not in seen:
            seen.add(match.name)
            names.append(match.name)
    return names


