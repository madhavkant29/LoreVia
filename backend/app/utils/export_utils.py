def manuscript_pdf_compiled(
    *,
    title: str,
    chapters: list[dict],
    scenes: list[dict] | None = None,
    preset: str = "standard_manuscript",
    front_matter: dict | None = None,
    font_family: str | None = None,
    include_toc: bool = False,
) -> bytes:
    from io import BytesIO

    from reportlab.lib.pagesizes import A4, A5, LETTER
    from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
    from reportlab.lib.units import inch
    from reportlab.platypus import PageBreak, Paragraph, SimpleDocTemplate, Spacer
    from reportlab.platypus.tableofcontents import TableOfContents

    def escaped(value: str) -> str:
        return value.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")

    export_preset = _manuscript_export_preset(preset)
    front = _manuscript_front_matter(title, chapters, front_matter)
    page_size = {"A4": A4, "A5": A5, "LETTER": LETTER}[str(export_preset["pdf_page_size"])]
    left_margin, right_margin, top_margin, bottom_margin = cast(tuple[float, float, float, float], export_preset["pdf_margins"])
    buffer = BytesIO()
    class ManuscriptPdfTemplate(SimpleDocTemplate):
        def afterFlowable(self, flowable) -> None:
            if not include_toc:
                return
            if not isinstance(flowable, Paragraph) or getattr(flowable.style, "name", "") != "ChapterHeading":
                return
            toc_label = getattr(flowable, "_lorevia_toc_label", None)
            if not toc_label:
                return
            self.notify("TOCEntry", (0, toc_label, self.page))

    template_class = ManuscriptPdfTemplate if include_toc else SimpleDocTemplate
    doc = template_class(
        buffer,
        pagesize=page_size,
        leftMargin=left_margin * inch,
        rightMargin=right_margin * inch,
        topMargin=top_margin * inch,
        bottomMargin=bottom_margin * inch,
    )
    styles = getSampleStyleSheet()
    pdf_regular, pdf_bold = _export_font_pdf_names(font_family)
    body = ParagraphStyle("ManuscriptBody", parent=styles["BodyText"], fontName=pdf_regular, fontSize=12, leading=24, firstLineIndent=0.5 * inch)
    body_first = ParagraphStyle("ManuscriptBodyFirst", parent=body, firstLineIndent=0)
    centered = ParagraphStyle("CenteredBody", parent=body, alignment=1, firstLineIndent=0)
    chapter_heading = ParagraphStyle("ChapterHeading", parent=styles["Heading2"], fontName=pdf_bold, fontSize=14, alignment=1, leading=18)
    title_style = ParagraphStyle("TitleStyle", parent=styles["Heading1"], fontName=pdf_bold, fontSize=18, alignment=1, leading=24)
    toc_entry_style = ParagraphStyle("ManuscriptTOCEntry", parent=styles["BodyText"], fontName=pdf_regular, fontSize=11, leading=18)

    story: list[Any] = []
    contact_lines = [line for line in [front["author_name"] or front["display_author"], front["contact_email"], front["contact_phone"], front["contact_address"]] if line]
    if contact_lines:
        story.append(Paragraph("<br/>".join(escaped(str(line)) for line in contact_lines), body))
    story.append(Paragraph(f"<para alignment='right'>{escaped(_approx_word_count_label(int(front['word_count'])))}</para>", body))
    story.append(Spacer(1, 2.0 * inch))
    story.append(Paragraph(escaped(front["title"]), title_style))
    if front["subtitle"]:
        story.append(Paragraph(escaped(front["subtitle"]), centered))
    story.append(Spacer(1, 0.3 * inch))
    story.append(Paragraph(escaped(front["display_author"] or " "), centered))

    if include_toc:
        toc = TableOfContents()
        toc.levelStyles = [toc_entry_style]
        story.append(PageBreak())
        story.append(Spacer(1, 0.6 * inch))
        story.append(Paragraph("Table of Contents", chapter_heading))
        story.append(Spacer(1, 0.3 * inch))
        story.append(toc)

    def _optional_page(heading: str, content: str) -> None:
        story.append(PageBreak())
        story.append(Spacer(1, 2.0 * inch))
        story.append(Paragraph(escaped(heading), chapter_heading))
        story.append(Spacer(1, 0.2 * inch))
        story.append(Paragraph(escaped(content), centered))

    if front["include_dedication"] and front["dedication"]:
        _optional_page("Dedication", front["dedication"])
    if front["include_epigraph"] and front["epigraph"]:
        _optional_page("Epigraph", front["epigraph"])
    if front["include_acknowledgments"] and front["acknowledgments"]:
        _optional_page("Acknowledgments", front["acknowledgments"])
    if front["include_prologue"] and front["prologue"]:
        _optional_page("Prologue", front["prologue"])

    def _append_body_text(body_text: str) -> None:
        first_paragraph = True
        for kind, block in _chapter_body_blocks(body_text):
            story.append(
                Paragraph(
                    "***" if kind == "scene_break" else escaped(block).replace("\n", "<br/>"),
                    centered if kind == "scene_break" else (body_first if first_paragraph else body),
                )
            )
            first_paragraph = kind == "scene_break"

    for chapter in chapters:
        story.append(PageBreak())
        chapter_heading_text, chapter_subtitle = _chapter_heading_lines(chapter)
        story.append(Spacer(1, 2.2 * inch))
        heading_paragraph = Paragraph(escaped(chapter_heading_text), chapter_heading)
        if include_toc:
            setattr(heading_paragraph, "_lorevia_toc_label", _manuscript_toc_label(chapter))
        story.append(heading_paragraph)
        if chapter_subtitle:
            story.append(Paragraph(escaped(chapter_subtitle), centered))
            story.append(Spacer(1, 0.1 * inch))
        _append_body_text(str(chapter.get("text") or ""))

    for index, scene in enumerate(scenes or [], start=1):
        scene_heading_text, scene_subtitle = _scene_heading_lines(scene, index)
        story.append(PageBreak())
        story.append(Spacer(1, 2.2 * inch))
        story.append(Paragraph(escaped(scene_heading_text), chapter_heading))
        if scene_subtitle:
            story.append(Paragraph(escaped(scene_subtitle), centered))
            story.append(Spacer(1, 0.1 * inch))
        _append_body_text(str(scene.get("body") or ""))

    story.append(PageBreak())
    story.append(Spacer(1, 2.2 * inch))
    story.append(Paragraph(_manuscript_end_marker(), chapter_heading))

    def _draw_first_page(canvas, doc_obj) -> None:
        _draw_later_pages(canvas, doc_obj)

    def _draw_later_pages(canvas, doc_obj) -> None:
        canvas.saveState()
        _apply_pdf_metadata(
            canvas,
            title=front["title"],
            author=front["display_author"] or "LoreVia",
            subject="Manuscript",
        )
        canvas.setFont(pdf_regular, 10)
        canvas.drawRightString(
            doc_obj.pagesize[0] - doc.rightMargin,
            doc_obj.pagesize[1] - 0.55 * inch,
            f"{front['header_last_name']} / {front['header_title']} / {canvas.getPageNumber()}",
        )
        canvas.restoreState()

    if include_toc:
        doc.multiBuild(story, onFirstPage=_draw_first_page, onLaterPages=_draw_later_pages)
    else:
        doc.build(story, onFirstPage=_draw_first_page, onLaterPages=_draw_later_pages)
    return buffer.getvalue()


def manuscript_epub_compiled(
    *,
    title: str,
    chapters: list[dict],
    scenes: list[dict] | None = None,
    preset: str = "standard_manuscript",
    front_matter: dict | None = None,
    font_family: str | None = None,
    include_toc: bool = False,
) -> bytes:
    from ebooklib import epub
    from html import escape
    import os
    import tempfile

    front = _manuscript_front_matter(title, chapters, front_matter)
    safe_title = _clean_line(front["title"]) or "LoreVia Manuscript Export"
    book = epub.EpubBook()
    book.set_identifier(_safe_name(safe_title) or "lorevia-manuscript")
    book.set_title(safe_title)
    book.set_language("en")
    if front["display_author"]:
        book.add_author(front["display_author"])

    stylesheet = epub.EpubItem(
        uid="style_nav",
        file_name="styles/main.css",
        media_type="text/css",
        content=(
            f"body {{ font-family: {_export_font_epub_stack(font_family)}; font-size: 12pt; line-height: 2; margin: 8%; }} "
            "h1, h2 { text-align: center; } "
            ".title-page, .end-marker { text-align: center; margin-top: 20%; } "
            ".toc-page { page-break-before: always; } "
            ".toc-page ol { line-height: 1.8; } "
            ".scene-break { text-align: center; letter-spacing: 0.2em; } "
            ".first-paragraph { text-indent: 0; } "
            "p { text-indent: 1.5em; margin: 0 0 1em; }"
        ).encode("utf-8"),
    )
    book.add_item(stylesheet)

    spine: list[Any] = ["nav"]
    toc_entries: list[Any] = []

    def _body_html(text: str) -> str:
        parts: list[str] = []
        first_paragraph = True
        for kind, block in _chapter_body_blocks(text):
            if kind == "scene_break":
                parts.append("<p class='scene-break'>***</p>")
                first_paragraph = True
                continue
            css_class = "first-paragraph" if first_paragraph else ""
            safe_block = escape(block).replace("\n", "<br/>")
            parts.append(f"<p class='{css_class}'>{safe_block}</p>" if css_class else f"<p>{safe_block}</p>")
            first_paragraph = False
        return "".join(parts) or "<p class='first-paragraph'></p>"

    title_page = epub.EpubHtml(title="Title Page", file_name="title-page.xhtml", lang="en")
    contact_lines = [
        line for line in [front["author_name"] or front["display_author"], front["contact_email"], front["contact_phone"], front["contact_address"]]
        if line
    ]
    title_page.content = (
        "<section class='title-page'>"
        f"<h1>{escape(front['title'])}</h1>"
        f"{f'<h2>{escape(front['subtitle'])}</h2>' if front['subtitle'] else ''}"
        f"<p class='first-paragraph'>{escape(front['display_author'] or ' ')}</p>"
        f"{''.join(f'<p class=\"first-paragraph\">{escape(str(line))}</p>' for line in contact_lines)}"
        f"<p class='first-paragraph'>{_approx_word_count_label(int(front['word_count']))}</p>"
        "</section>"
    )
    title_page.add_item(stylesheet)
    book.add_item(title_page)
    spine.append(title_page)
    toc_entries.append(title_page)

    if include_toc:
        toc_item = epub.EpubHtml(title="Table of Contents", file_name="table-of-contents.xhtml", lang="en")
        toc_items = []
        for chapter in chapters:
            chapter_number = chapter.get("number")
            toc_items.append(
                f"<li><a href='chapter-{chapter_number}.xhtml'>{escape(_manuscript_toc_label(chapter))}</a></li>"
            )
        toc_item.content = "<section class='toc-page'><h1>Table of Contents</h1><ol>" + "".join(toc_items) + "</ol></section>"
        toc_item.add_item(stylesheet)
        book.add_item(toc_item)
        spine.append(toc_item)
        toc_entries.append(toc_item)

    optional_sections: list[tuple[str, str]] = []
    if front["include_dedication"] and front["dedication"]:
        optional_sections.append(("Dedication", front["dedication"]))
    if front["include_epigraph"] and front["epigraph"]:
        optional_sections.append(("Epigraph", front["epigraph"]))
    if front["include_acknowledgments"] and front["acknowledgments"]:
        optional_sections.append(("Acknowledgments", front["acknowledgments"]))
    if front["include_prologue"] and front["prologue"]:
        optional_sections.append(("Prologue", front["prologue"]))

    for index, (heading, content) in enumerate(optional_sections, start=1):
        item = epub.EpubHtml(title=heading, file_name=f"front-{index}.xhtml", lang="en")
        item.content = f"<h1>{escape(heading)}</h1><p class='first-paragraph'>{escape(content)}</p>"
        item.add_item(stylesheet)
        book.add_item(item)
        spine.append(item)
        toc_entries.append(item)

    for chapter in chapters:
        chapter_number = chapter.get("number")
        chapter_heading_text, chapter_subtitle = _chapter_heading_lines(chapter)
        item = epub.EpubHtml(
            title=chapter_subtitle or chapter_heading_text,
            file_name=f"chapter-{chapter_number}.xhtml",
            lang="en",
        )
        item.content = (
            f"<h1>{escape(chapter_heading_text)}</h1>"
            f"{f'<h2>{escape(chapter_subtitle)}</h2>' if chapter_subtitle else ''}"
            f"{_body_html(str(chapter.get('text') or ''))}"
        )
        item.add_item(stylesheet)
        book.add_item(item)
        spine.append(item)
        toc_entries.append(item)

    for index, scene in enumerate(scenes or [], start=1):
        scene_heading_text, scene_subtitle = _scene_heading_lines(scene, index)
        item = epub.EpubHtml(
            title=scene_subtitle or scene_heading_text,
            file_name=f"scene-{index}.xhtml",
            lang="en",
        )
        item.content = (
            f"<h1>{escape(scene_heading_text)}</h1>"
            f"{f'<h2>{escape(scene_subtitle)}</h2>' if scene_subtitle else ''}"
            f"{_body_html(str(scene.get('body') or ''))}"
        )
        item.add_item(stylesheet)
        book.add_item(item)
        spine.append(item)
        toc_entries.append(item)

    ending = epub.EpubHtml(title="The End", file_name="the-end.xhtml", lang="en")
    ending.content = f"<section class='end-marker'><h1>{_manuscript_end_marker()}</h1></section>"
    ending.add_item(stylesheet)
    book.add_item(ending)
    spine.append(ending)
    toc_entries.append(ending)

    book.toc = tuple(toc_entries)
    book.spine = spine
    book.add_item(epub.EpubNcx())
    book.add_item(epub.EpubNav())
    with tempfile.TemporaryDirectory() as tmpdir:
        target = os.path.join(tmpdir, "manuscript.epub")
        epub.write_epub(target, book, {})
        with open(target, "rb") as handle:
            return handle.read()


